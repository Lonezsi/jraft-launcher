// Source is pack/pack.json, the human-edited list of what goes in the pack.
type Source struct {
	Name      string `json:"name"`
	Minecraft string `json:"minecraft"`
	// ResourceFormat is this Minecraft version's resource pack format, "major.minor"
	// (version.json's pack_version in the client jar; 97.1 for 26.3). The launcher
	// compares each resource pack against it. Change it together with Minecraft.
	ResourceFormat       string   `json:"resourceFormat,omitempty"`
	Loader               string   `json:"loader"`
	JavaArgs             string   `json:"javaArgs"`
	Mods                 []string `json:"mods"`
	Resourcepacks        []string `json:"resourcepacks"`
	Shaderpacks          []string `json:"shaderpacks"`
	EnabledResourcepacks []string `json:"enabledResourcepacks"`
	Extra                []File   `json:"extra"`
	// Pins holds a project to one exact Modrinth version_number instead of the newest
	// build. Used when another mod only works with a specific version.
	Pins map[string]string `json:"pins,omitempty"`
	// ForceOverrides are files under pack/overrides that every install gets again,
	// once, whenever OverridesRevision goes up, even if the player already has them.
	// Raise the revision after changing one of them on purpose.
	ForceOverrides    []string `json:"forceOverrides,omitempty"`
	OverridesRevision int      `json:"overridesRevision,omitempty"`
	// IgnoreDependencies are Modrinth project ids that some projects list as required
	// but that this Minecraft version does not need, such as backports of a feature
	// the game now has built in.
	IgnoreDependencies []string `json:"ignoreDependencies,omitempty"`
	// Strip lists, per project, paths inside its zip that the launcher deletes after
	// downloading it. A path ending in "/" removes everything under it. Used to cut a
	// broken part out of a pack whose license doesn't let us host a fixed copy.
	Strip map[string][]string `json:"strip,omitempty"`
	// Server, when set, is joined on launch through the launcher's relay.
	Server *Server `json:"server,omitempty"`
}

// Lock is pack/lock.json, generated by lockgen and read by the launcher.
type Lock struct {
	Name      string `json:"name"`
	Minecraft string `json:"minecraft"`
	// See Source.
	ResourceFormat string `json:"resourceFormat,omitempty"`
	LoaderVersion  string `json:"loaderVersion"`
	JavaArgs       string `json:"javaArgs"`
	// Files are kept in sync on every run (mods, resource packs, shaders).
	Files []File `json:"files"`
	// Overrides live in pack/overrides and are copied only when missing,
	// so friends can change their own settings.
	Overrides []File `json:"overrides"`
	// ResourcePacks are the packs the pack turns on, bottom to top: the last one wins.
	// They are written into options.txt whenever this list changes.
	ResourcePacks []string `json:"resourcePacks"`
	// See Source.
	ForceOverrides    []string `json:"forceOverrides,omitempty"`
	OverridesRevision int      `json:"overridesRevision,omitempty"`
	Server            *Server  `json:"server,omitempty"`
	Skipped           []string `json:"skipped,omitempty"`
}

type File struct {
	Path    string `json:"path"`
	URL     string `json:"url,omitempty"`
	SHA512  string `json:"sha512"`
	Size    int64  `json:"size,omitempty"`
	Comment string `json:"comment,omitempty"`
	// Strip is copied from Source.Strip: zip paths removed after download.
	Strip []string `json:"strip,omitempty"`
	// Local is a file kept in this repository, as a path under pack/ (the merge resource
	// packs in pack/packs/). The launcher fetches it from its own repository and branch,
	// or from JRAFT_PACK_DIR; URL is the same file on main, for older launchers.
	Local string `json:"local,omitempty"`
}

// StateKey is what the launcher remembers for an installed file: its sha512, plus
// what was stripped from it, so changing Strip makes the file get fetched again.
func (f File) StateKey() string {
	if len(f.Strip) == 0 {
		return f.SHA512
	}
	return f.SHA512 + " strip:" + strings.Join(f.Strip, ",")
}

func (l Lock) FabricID() string {
	return fmt.Sprintf("fabric-loader-%s-%s", l.LoaderVersion, l.Minecraft)
}

// SafePath rejects absolute paths and anything escaping the instance folder.
func SafePath(p string) error {
	c := path.Clean(p)
	if p == "" || path.IsAbs(c) || c == ".." || strings.HasPrefix(c, "../") || strings.Contains(p, "\\") || strings.Contains(p, ":") {
		return fmt.Errorf("unsafe path in lock file: %q", p)
	}
	return nil
}

func HashFile(name string) (string, error) {
	f, err := os.Open(name)
	if err != nil {
		return "", err
	}
	defer f.Close()
	h := sha512.New()
	if _, err := io.Copy(h, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// StripZip rewrites the zip at name without the entries matching strip (exact paths,
// or everything under a path ending in "/"). Kept entries are copied as they are.
func StripZip(name string, strip []string) error {
	r, err := zip.OpenReader(name)
	if err != nil {
		return err
	}
	tmp := name + ".strip"
	out, err := os.Create(tmp)
	if err != nil {
		r.Close()
		return err
	}
	w := zip.NewWriter(out)
	for _, f := range r.File {
		drop := false
		for _, s := range strip {
			drop = drop || f.Name == s || (strings.HasSuffix(s, "/") && strings.HasPrefix(f.Name, s))
		}
		if !drop {
			if err = w.Copy(f); err != nil {
				break
			}
		}
	}
	if err == nil {
		err = w.Close()
	}
	out.Close()
	r.Close()
	if err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, name)
}

// Server is the pack's own server, reached through the launcher's relay.
type Server struct {
	Name    string `json:"name"`
	Address string `json:"address"` // host:port of the TLS (Funnel) endpoint
}

// PackCompatible reports whether a resource pack's pack.mcmeta accepts the resource
// format format ("major.minor"), the way Minecraft decides it: min_format/max_format
// when present, otherwise supported_formats, otherwise pack_format alone. A bare major
// number as a maximum covers all of that major's minor versions.
func PackCompatible(mcmeta []byte, format string) (bool, error) {
	want, err := parseFormat(json.Number(format), true)
	if err != nil {
		return false, err
	}
	var meta struct {
		Pack map[string]json.RawMessage `json:"pack"`
	}
	mcmeta = bytes.TrimPrefix(mcmeta, []byte("\xef\xbb\xbf")) // some packs start with a byte order mark
	d := json.NewDecoder(bytes.NewReader(mcmeta))
	d.UseNumber()
	if err := d.Decode(&meta); err != nil {
		return false, err
	}
	p := meta.Pack
	within := func(lo, hi any) (bool, error) {
		l, err := parseFormat(lo, true)
		if err != nil {
			return false, err
		}
		h, err := parseFormat(hi, false)
		if err != nil {
			return false, err
		}
		return !less(want, l) && !less(h, want), nil
	}
	value := func(raw json.RawMessage) any {
		var v any
		d := json.NewDecoder(bytes.NewReader(raw))
		d.UseNumber()
		d.Decode(&v)
		return v
	}
	if lo, ok := p["min_format"]; ok {
		hi, ok := p["max_format"]
		if !ok {
			return false, fmt.Errorf("min_format without max_format")
		}
		return within(value(lo), value(hi))
	}
	if sf, ok := p["supported_formats"]; ok {
		switch v := value(sf).(type) {
		case []any:
			if len(v) == 2 {
				return within(v[0], v[1])
			}
		case map[string]any:
			return within(v["min_inclusive"], v["max_inclusive"])
		case json.Number:
			return within(v, v)
		}
		return false, fmt.Errorf("unreadable supported_formats")
	}
	if pf, ok := p["pack_format"]; ok {
		return within(value(pf), value(pf))
	}
	return false, fmt.Errorf("no pack format")
}

type format struct{ major, minor int }

func less(a, b format) bool {
	return a.major < b.major || a.major == b.major && a.minor < b.minor
}

// parseFormat reads 97, 97.1 or [97, 1]. A lone major is .0 as a lower bound and
// covers every minor as an upper bound.
func parseFormat(v any, low bool) (format, error) {
	switch x := v.(type) {
	case json.Number:
		major, minor, hasMinor := strings.Cut(x.String(), ".")
		a, err := strconv.Atoi(major)
		if err != nil {
			return format{}, err
		}
		if !hasMinor {
			if low {
				return format{a, 0}, nil
			}
			return format{a, math.MaxInt}, nil
		}
		b, err := strconv.Atoi(minor)
		return format{a, b}, err
	case []any:
		if len(x) == 0 || len(x) > 2 {
			break
		}
		if len(x) == 1 {
			return parseFormat(x[0], low)
		}
		a, err1 := parseFormat(x[0], true)
		b, err2 := parseFormat(x[1], true)
		if err1 != nil || err2 != nil {
			break
		}
		return format{a.major, b.major}, nil
	}
	return format{}, fmt.Errorf("unreadable pack format %v", v)
}
